export let menuData = JSON.parse(JSON.stringify(DEFAULT_MENU_DATA));

export function setMenuData(categories) {
    if (!Array.isArray(categories) || categories.length === 0) return false;
    // Filtrar categorías activas y productos activos para la vista pública
    const filtered = categories
        .filter(cat => cat.active !== false)
        .map(cat => ({
            ...cat,
            items: (cat.items || []).filter(it => it.active !== false)
        }))
        .filter(cat => cat.items.length > 0);

    menuData = filtered;
    return true;
}

export function findProductConfigById(productId) {
    const baseId = String(productId || '').split('_')[0];
    for (const cat of menuData) {
        for (const it of (cat.items || [])) {
            if (it.id === productId || it.id === baseId) {
                return it;
            }
        }
    }
    return null;
}

